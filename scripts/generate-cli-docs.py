#!/usr/bin/env python3
"""Regenerate docs/cli-raw.md from the built binary's --help output.

Usage: cargo build --workspace && python scripts/generate-cli-docs.py

The script shells out to the debug binary; it never edits source. On any
drift between the checked-in docs/cli-raw.md and the binary, it rewrites the file
and prints a summary. CI runs it with --check to fail on drift.
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.path.join(ROOT, "target", "debug", "watchdog" + (".exe" if os.name == "nt" else ""))

TOPLEVEL = [
    ["version"],
    ["doctor"],
    ["config", "show"],
    ["config", "path"],
    ["config", "validate"],
    ["serve"],
    ["device", "list"],
    ["device", "discover"],
    ["device", "connect"],
    ["device", "pair"],
    ["device", "disconnect"],
    ["device", "info"],
    ["device", "shell"],
    ["device", "push"],
    ["device", "pull"],
    ["device", "install"],
    ["device", "uninstall"],
    ["device", "forward"],
    ["device", "logs"],
    ["device", "provision"],
    ["device", "status"],
    ["device", "restore"],
    ["device", "udev-rules"],
    ["device", "usb-doctor"],
    ["device", "capabilities"],
    ["capture", "still"],
    ["capture", "burst"],
    ["capture", "record", "start"],
    ["capture", "record", "stop"],
    ["analyze", "run"],
    ["analyze", "report"],
    ["analyze", "list-analyzers"],
    ["schedule", "add"],
    ["schedule", "list"],
    ["schedule", "run"],
    ["schedule", "enable"],
    ["schedule", "disable"],
    ["schedule", "rm"],
    ["media", "list"],
    ["media", "get"],
    ["media", "export"],
    ["media", "rm"],
    ["mcp"],
]

HEADER = """# CLI reference (auto-generated)

Generated by `scripts/generate-cli-docs.py --check` in CI from the clap
definitions. Do not edit by hand; edit the CLI and regenerate.

Exit codes: `0` ok, `1` runtime error, `2` CLI misuse.

"""


def help_text(args):
    result = subprocess.run([BIN, *args, "--help"], capture_output=True, text=True, check=True)
    return result.stdout.rstrip()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if docs/cli-raw.md is stale instead of rewriting it")
    args = parser.parse_args()
    if not os.path.exists(BIN):
        print(f"binary not found at {BIN}; build first (cargo build --workspace)", file=sys.stderr)
        return 1

    parts = [HEADER]
    parts.append("## Global flags\n\nGlobal flags apply to every command (see `watchdog --help`).\n\n")
    global_help = help_text([])
    parts.append("```\n" + global_help + "\n```\n\n")

    for command in TOPLEVEL:
        parts.append("## `watchdog " + " ".join(command) + "`\n\n```\n" + help_text(command) + "\n```\n\n")

    content = "".join(parts)
    target = os.path.join(ROOT, "docs", "cli.md")
    if args.check:
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        if current != content:
            print("docs/cli-raw.md is stale; run scripts/generate-cli-docs.py", file=sys.stderr)
            return 1
        print("docs/cli-raw.md is up to date")
        return 0
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print("wrote docs/cli-raw.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
